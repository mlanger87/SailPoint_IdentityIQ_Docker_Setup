#!/usr/bin/env python3
# ===========================================================================
# SCIM 2.0 server as target system for the SCIM2Connector
# ===========================================================================
# Implements the part of RFC 7643/7644 that IdentityIQ's SCIM 2.0
# connector actually uses:
#
#   GET          /ServiceProviderConfig        capabilities (no token needed;
#                                              doubles as the health check)
#   GET          /ResourceTypes[/{id}]
#   GET          /Schemas[/{urn}]
#   GET, POST    /Users                        list (filter, paging), create
#   GET, PUT,
#   PATCH, DELETE /Users/{id}
#   GET, POST    /Groups
#   GET, PUT,
#   PATCH, DELETE /Groups/{id}
#
# Why not a third-party SCIM server: the one used before (harrykodden/scim)
# stores group membership only on the Group resource and never derives the
# read-only "groups" attribute of a User. The connector aggregates account
# entitlements from exactly that attribute (groups[*].value), so every role
# with SCIM entitlements would have been re-provisioned on every refresh and
# never detected. Here "groups" is computed from Groups.members on every
# read, as RFC 7643 section 4.1.2 describes it.
#
# Deliberately no framework, like the REST mock: the standard library is
# enough, the image stays at ~50 MB and there is no dependency to pin.
#
# Data lives in memory and is seeded at start from /data/seed
# (scim-users.json, scim-groups.json, both generated by
# scripts/generate-testdata.py). A restart therefore brings the seed
# back on its own; nothing has to be replayed by hand.
#
# Authentication: "Authorization: Bearer <API_KEY>" on every resource
# endpoint. That matches authType="oauthBearer" in the application.
# ===========================================================================
import json
import os
import re
import threading
import uuid
from datetime import datetime, timezone
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path
from urllib.parse import parse_qs, unquote, urlparse

API_KEY = os.environ.get("API_KEY", "secret")
PORT = int(os.environ.get("PORT", "8000"))
SEED_DIR = Path(os.environ.get("SEED_DIR", "/data/seed"))
# Base URL used in meta.location and $ref. The connector does not follow
# them; they only have to be well-formed.
BASE_URL = os.environ.get("BASE_URL", f"http://scim:{PORT}")

SCHEMA_USER = "urn:ietf:params:scim:schemas:core:2.0:User"
SCHEMA_GROUP = "urn:ietf:params:scim:schemas:core:2.0:Group"
SCHEMA_LIST = "urn:ietf:params:scim:api:messages:2.0:ListResponse"
SCHEMA_PATCH = "urn:ietf:params:scim:api:messages:2.0:PatchOp"
SCHEMA_ERROR = "urn:ietf:params:scim:api:messages:2.0:Error"
SCHEMA_SPC = "urn:ietf:params:scim:schemas:core:2.0:ServiceProviderConfig"
SCHEMA_RT = "urn:ietf:params:scim:schemas:core:2.0:ResourceType"
SCHEMA_SCHEMA = "urn:ietf:params:scim:schemas:core:2.0:Schema"

# Attributes that are multi-valued complex lists on the resources served
# here. PATCH treats them as lists (append / remove elements), everything
# else as a scalar or a sub-object.
MULTI_VALUED = {"emails", "members", "groups", "phoneNumbers", "addresses"}
# Attributes the client may not write; they are derived or server-owned.
READ_ONLY = {"id", "meta", "groups", "schemas"}

_lock = threading.Lock()
_users: dict[str, dict] = {}
_groups: dict[str, dict] = {}


def now() -> str:
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def stable_id(kind: str, key: str) -> str:
    """
    Deterministic id, so a container restart (or a test-data regeneration
    with the same seed) yields the same ids and role definitions that
    reference group ids stay valid.
    """
    return str(uuid.uuid5(uuid.NAMESPACE_URL, f"scim:{kind}:{key}"))


class ScimError(Exception):
    def __init__(self, status: int, detail: str, scim_type: str | None = None):
        super().__init__(detail)
        self.status = status
        self.detail = detail
        self.scim_type = scim_type


# ---------------------------------------------------------------------------
# Filter parsing (RFC 7644 section 3.4.2.2)
#
# Grammar covered:  expr := term (('and'|'or') term)*
#                   term := 'not'? '(' expr ')'
#                         | attrPath '[' expr ']'          (value filter)
#                         | attrPath 'pr'
#                         | attrPath op value
# Enough for what the connector and this landscape send:
#   externalId eq "1031", userName eq "x", members[value eq "<id>"].
# ---------------------------------------------------------------------------
_TOKEN = re.compile(
    r'\s*(?:(?P<lp>\()|(?P<rp>\))|(?P<lb>\[)|(?P<rb>\])'
    r'|(?P<str>"(?:[^"\\]|\\.)*")|(?P<word>[A-Za-z0-9_.:$\-]+))')


def _tokenize(text: str) -> list[tuple[str, str]]:
    pos, out = 0, []
    while pos < len(text):
        m = _TOKEN.match(text, pos)
        if not m or m.end() == pos:
            raise ScimError(400, f"invalid filter near: {text[pos:pos + 20]}", "invalidFilter")
        pos = m.end()
        kind = m.lastgroup
        if kind:
            out.append((kind, m.group(kind)))
    return out


class _Parser:
    def __init__(self, tokens: list[tuple[str, str]]):
        self.t = tokens
        self.i = 0

    def peek(self):
        return self.t[self.i] if self.i < len(self.t) else (None, None)

    def take(self):
        tok = self.peek()
        self.i += 1
        return tok

    def parse(self):
        node = self.expr()
        if self.peek()[0] is not None:
            raise ScimError(400, "unexpected token in filter", "invalidFilter")
        return node

    def expr(self):
        left = self.term()
        while self.peek()[0] == "word" and self.peek()[1].lower() in ("and", "or"):
            op = self.take()[1].lower()
            right = self.term()
            left = (op, left, right)
        return left

    def term(self):
        kind, val = self.peek()
        if kind == "word" and val.lower() == "not":
            self.take()
            return ("not", self.term())
        if kind == "lp":
            self.take()
            node = self.expr()
            if self.take()[0] != "rp":
                raise ScimError(400, "missing ) in filter", "invalidFilter")
            return node
        if kind != "word":
            raise ScimError(400, "attribute expected in filter", "invalidFilter")
        attr = self.take()[1]
        kind, val = self.peek()
        if kind == "lb":
            self.take()
            sub = self.expr()
            if self.take()[0] != "rb":
                raise ScimError(400, "missing ] in filter", "invalidFilter")
            return ("any", attr, sub)
        if kind == "word" and val.lower() == "pr":
            self.take()
            return ("pr", attr)
        if kind != "word":
            raise ScimError(400, "operator expected in filter", "invalidFilter")
        op = self.take()[1].lower()
        kind, val = self.take()
        if kind == "str":
            value = json.loads(val)
        elif kind == "word":
            value = {"true": True, "false": False, "null": None}.get(val.lower(), val)
        else:
            raise ScimError(400, "value expected in filter", "invalidFilter")
        return ("cmp", attr, op, value)


def parse_filter(text: str | None):
    if not text:
        return None
    return _Parser(_tokenize(text)).parse()


def _lookup(resource: dict, path: str):
    """Resolves a dotted attribute path; lists yield lists of sub-values."""
    # A schema-qualified path (urn:...:User:userName) reduces to its tail.
    if path.startswith("urn:"):
        path = path.rsplit(":", 1)[-1]
    cur = resource
    for part in path.split("."):
        if isinstance(cur, list):
            cur = [c.get(part) if isinstance(c, dict) else None for c in cur]
            cur = [c for c in cur if c is not None]
        elif isinstance(cur, dict):
            key = next((k for k in cur if k.lower() == part.lower()), None)
            cur = cur.get(key) if key else None
        else:
            return None
        if cur is None:
            return None
    return cur


def _compare(actual, op: str, expected) -> bool:
    if isinstance(actual, list):
        return any(_compare(a, op, expected) for a in actual)
    if isinstance(actual, dict):
        actual = actual.get("value")
    if actual is None:
        return op == "ne"
    if isinstance(actual, bool) or isinstance(expected, bool):
        a, e = str(actual).lower(), str(expected).lower()
    else:
        a, e = str(actual).lower(), str(expected).lower()
    return {
        "eq": a == e, "ne": a != e, "co": e in a, "sw": a.startswith(e),
        "ew": a.endswith(e), "gt": a > e, "ge": a >= e, "lt": a < e, "le": a <= e,
    }.get(op, False)


def matches(resource: dict, node) -> bool:
    if node is None:
        return True
    kind = node[0]
    if kind == "and":
        return matches(resource, node[1]) and matches(resource, node[2])
    if kind == "or":
        return matches(resource, node[1]) or matches(resource, node[2])
    if kind == "not":
        return not matches(resource, node[1])
    if kind == "pr":
        return _lookup(resource, node[1]) not in (None, [], "")
    if kind == "any":
        values = _lookup(resource, node[1])
        if not isinstance(values, list):
            values = [values] if values is not None else []
        return any(isinstance(v, dict) and matches(v, node[2]) for v in values)
    if kind == "cmp":
        return _compare(_lookup(resource, node[1]), node[2], node[3])
    return False


