def service_provider_config() -> dict:
    return {
        "schemas": [SCHEMA_SPC],
        "documentationUri": "https://www.rfc-editor.org/rfc/rfc7644",
        "patch": {"supported": True},
        "bulk": {"supported": False, "maxOperations": 0, "maxPayloadSize": 0},
        "filter": {"supported": True, "maxResults": 1000},
        "changePassword": {"supported": False},
        "sort": {"supported": False},
        "etag": {"supported": False},
        "authenticationSchemes": [{
            "type": "oauthbearertoken",
            "name": "OAuth Bearer Token",
            "description": "Static bearer token (API_KEY)",
            "primary": True,
        }],
        "meta": {"resourceType": "ServiceProviderConfig",
                 "location": f"{BASE_URL}/ServiceProviderConfig"},
    }


def _attr(name, typ="string", multi=False, required=False, mutability="readWrite",
          returned="default", uniqueness="none", sub=None, case_exact=False):
    a = {"name": name, "type": typ, "multiValued": multi, "description": name,
         "required": required, "caseExact": case_exact, "mutability": mutability,
         "returned": returned, "uniqueness": uniqueness}
    if sub:
        a["subAttributes"] = sub
    return a


def schemas() -> list[dict]:
    ref_sub = [_attr("value"), _attr("display", mutability="readOnly"),
               _attr("$ref", typ="reference")]
    return [
        {"schemas": [SCHEMA_SCHEMA], "id": SCHEMA_USER, "name": "User",
         "description": "User Account",
         "attributes": [
             _attr("userName", required=True, uniqueness="server"),
             _attr("externalId", uniqueness="server"),
             _attr("name", typ="complex", sub=[_attr("givenName"), _attr("familyName"),
                                               _attr("formatted")]),
             _attr("displayName"),
             _attr("emails", typ="complex", multi=True,
                   sub=[_attr("value"), _attr("type"), _attr("primary", typ="boolean")]),
             _attr("title"),
             _attr("active", typ="boolean"),
             _attr("groups", typ="complex", multi=True, mutability="readOnly", sub=ref_sub),
         ],
         "meta": {"resourceType": "Schema", "location": f"{BASE_URL}/Schemas/{SCHEMA_USER}"}},
        {"schemas": [SCHEMA_SCHEMA], "id": SCHEMA_GROUP, "name": "Group",
         "description": "Group",
         "attributes": [
             _attr("displayName", required=True, uniqueness="server"),
             _attr("members", typ="complex", multi=True, sub=ref_sub),
         ],
         "meta": {"resourceType": "Schema", "location": f"{BASE_URL}/Schemas/{SCHEMA_GROUP}"}},
    ]


