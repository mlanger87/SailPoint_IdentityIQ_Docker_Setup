def list_response(items: list[dict], query: dict) -> dict:
    try:
        start = max(1, int(query.get("startIndex", ["1"])[0]))
        count = int(query.get("count", [str(len(items) or 1)])[0])
    except ValueError:
        raise ScimError(400, "startIndex and count must be integers", "invalidValue")
    if count < 0:
        count = 0
    page = items[start - 1:start - 1 + count]
    return {"schemas": [SCHEMA_LIST], "totalResults": len(items),
            "itemsPerPage": len(page), "startIndex": start, "Resources": page}


# ---------------------------------------------------------------------------
# Seed
# ---------------------------------------------------------------------------
def load_seed() -> None:
    users_file = SEED_DIR / "scim-users.json"
    groups_file = SEED_DIR / "scim-groups.json"
    if not users_file.is_file():
        print(f"[scim] {users_file} not found - starting empty.")
        return
    try:
        users = json.loads(users_file.read_text(encoding="utf-8"))
        groups = json.loads(groups_file.read_text(encoding="utf-8")) if groups_file.is_file() else []
    except (OSError, ValueError) as e:
        print(f"[scim] seed not readable ({e}) - starting empty.")
        return

    by_external: dict[str, str] = {}
    for raw in users:
        user = normalize_user(raw, None)
        uid = raw.get("id") or stable_id("user", user.get("externalId") or user["userName"])
        user["id"] = uid
        user["meta"] = meta("User", uid)
        validate_user(user, uid)
        _users[uid] = user
        if user.get("externalId"):
            by_external[user["externalId"]] = uid

    unknown = 0
    for raw in groups:
        gid = raw.get("id") or stable_id("group", raw["displayName"])
        members = []
        for ext in raw.get("members", []):
            uid = by_external.get(str(ext))
            if uid:
                members.append({"value": uid})
            else:
                unknown += 1
        group = normalize_group({"displayName": raw["displayName"], "members": members})
        group["id"] = gid
        group["meta"] = meta("Group", gid)
        validate_group(group, gid)
        _groups[gid] = group
    print(f"[scim] seed: {len(_users)} users, {len(_groups)} groups"
          + (f", {unknown} member references without a seed user (ignored)" if unknown else ""))


