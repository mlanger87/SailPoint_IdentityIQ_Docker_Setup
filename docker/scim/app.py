class Handler(BaseHTTPRequestHandler):
    server_version = "scim-target/1.0"

    def log_message(self, fmt, *args):
        status = args[1] if len(args) > 1 else "-"
        print(f"[scim] {self.command} {self.path} -> {status}")

    # -- plumbing ---------------------------------------------------------
    def _send(self, status: int, payload=None, location: str | None = None) -> None:
        body = json.dumps(payload).encode() if payload is not None else b""
        self.send_response(status)
        if body:
            self.send_header("Content-Type", "application/scim+json; charset=utf-8")
        self.send_header("Content-Length", str(len(body)))
        if location:
            self.send_header("Location", location)
        self.end_headers()
        if body:
            self.wfile.write(body)

    def _error(self, status: int, detail: str, scim_type: str | None = None) -> None:
        payload = {"schemas": [SCHEMA_ERROR], "status": str(status), "detail": detail}
        if scim_type:
            payload["scimType"] = scim_type
        self._send(status, payload)

    def _authorized(self) -> bool:
        return self.headers.get("Authorization", "") == f"Bearer {API_KEY}"

    def _json(self):
        length = int(self.headers.get("Content-Length") or 0)
        raw = self.rfile.read(length) if length else b""
        if not raw.strip():
            return {}
        try:
            data = json.loads(raw)
        except ValueError:
            raise ScimError(400, "request body is not valid JSON", "invalidSyntax")
        if not isinstance(data, dict):
            raise ScimError(400, "request body must be a JSON object", "invalidSyntax")
        return data

    def _route(self):
        parsed = urlparse(self.path)
        path = unquote(parsed.path).rstrip("/")
        # Tolerate the common /scim/v2 prefix so the base URL can be either.
        if path.startswith("/scim/v2"):
            path = path[len("/scim/v2"):]
        return path, parse_qs(parsed.query)

    def _dispatch(self):
        path, query = self._route()
        try:
            if self.command == "GET" and path == "/ServiceProviderConfig":
                return self._send(200, service_provider_config())
            if not self._authorized():
                return self._error(401, "invalid or missing bearer token", "invalidCredentials")
            with _lock:
                self._handle(path, query)
        except ScimError as e:
            self._error(e.status, e.detail, e.scim_type)
        except Exception as e:  # noqa: BLE001 - a mock must never die on a request
            self._error(500, f"internal error: {e}")

    def _handle(self, path: str, query: dict) -> None:
        m = self.command
        if m == "GET" and path == "/Schemas":
            return self._send(200, list_response(schemas(), query))
        if m == "GET" and path.startswith("/Schemas/"):
            urn = path[len("/Schemas/"):]
            for s in schemas():
                if s["id"] == urn:
                    return self._send(200, s)
            raise ScimError(404, f"schema {urn} not found")
        if m == "GET" and path == "/ResourceTypes":
            return self._send(200, list_response(resource_types(), query))
        if m == "GET" and path.startswith("/ResourceTypes/"):
            rid = path[len("/ResourceTypes/"):]
            for r in resource_types():
                if r["id"] == rid:
                    return self._send(200, r)
            raise ScimError(404, f"resource type {rid} not found")

        for prefix, store, out, kind in (("/Users", _users, user_out, "User"),
                                         ("/Groups", _groups, group_out, "Group")):
            if path == prefix:
                if m == "GET":
                    node = parse_filter(query.get("filter", [None])[0])
                    items = [out(r) for r in store.values() if matches(out(r), node)]
                    return self._send(200, list_response(items, query))
                if m == "POST":
                    return self._create(kind, store, out)
                raise ScimError(405, f"{m} not allowed on {prefix}")
            if path.startswith(prefix + "/"):
                rid = path[len(prefix) + 1:]
                if rid not in store:
                    raise ScimError(404, f"{kind} {rid} not found")
                if m == "GET":
                    return self._send(200, out(store[rid]))
                if m == "PUT":
                    return self._replace(kind, store, out, rid)
                if m == "PATCH":
                    return self._patch(kind, store, out, rid)
                if m == "DELETE":
                    return self._delete(kind, store, rid)
                raise ScimError(405, f"{m} not allowed on {path}")
        raise ScimError(404, f"unknown path: {path}")

    # -- resource operations -----------------------------------------------
    def _create(self, kind: str, store: dict, out) -> None:
        body = self._json()
        if kind == "User":
            res = normalize_user(body, None)
            rid = stable_id("user", res.get("externalId") or res["userName"])
            if rid in store:
                rid = str(uuid.uuid4())
            res["id"] = rid
            validate_user(res, rid)
        else:
            res = normalize_group(body)
            rid = stable_id("group", res.get("displayName", ""))
            if rid in store:
                rid = str(uuid.uuid4())
            res["id"] = rid
            validate_group(res, rid)
        res["meta"] = meta(kind, rid)
        store[rid] = res
        self._send(201, out(res), res["meta"]["location"])

    def _replace(self, kind: str, store: dict, out, rid: str) -> None:
        body = self._json()
        old = store[rid]
        res = normalize_user(body, old) if kind == "User" else normalize_group(body)
        res["id"] = rid
        res["meta"] = meta(kind, rid, old["meta"]["created"])
        (validate_user if kind == "User" else validate_group)(res, rid)
        store[rid] = res
        self._send(200, out(res))

    def _patch(self, kind: str, store: dict, out, rid: str) -> None:
        body = self._json()
        if SCHEMA_PATCH not in (body.get("schemas") or []):
            raise ScimError(400, f"schemas must contain {SCHEMA_PATCH}", "invalidSyntax")
        ops = body.get("Operations")
        if not isinstance(ops, list) or not ops:
            raise ScimError(400, "Operations must be a non-empty list", "invalidSyntax")
        old = store[rid]
        res = apply_patch(old, ops)
        res["id"] = rid
        res["meta"] = meta(kind, rid, old["meta"]["created"])
        if kind == "Group":
            res = normalize_group(res) | {"id": rid, "meta": res["meta"]}
        (validate_user if kind == "User" else validate_group)(res, rid)
        store[rid] = res
        self._send(200, out(res))

    def _delete(self, kind: str, store: dict, rid: str) -> None:
        del store[rid]
        if kind == "User":
            for g in _groups.values():
                g["members"] = [x for x in g.get("members", []) if x.get("value") != rid]
        self._send(204)

    def do_GET(self):
        self._dispatch()

    def do_POST(self):
        self._dispatch()

    def do_PUT(self):
        self._dispatch()

    def do_PATCH(self):
        self._dispatch()

    def do_DELETE(self):
        self._dispatch()


