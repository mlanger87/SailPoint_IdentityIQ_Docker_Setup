def unflatten(body: dict) -> dict:
    """
    Accepts both the nested form ({"name": {"givenName": ...}}) and the
    flattened form some clients send ({"name.givenName": ...},
    {"emails.value": ...}). Multi-valued paths become one-element lists.
    """
    out: dict = {}
    for key, value in body.items():
        if "." not in key or key.startswith("urn:"):
            out[key] = value
            continue
        head, tail = key.split(".", 1)
        if head in MULTI_VALUED:
            lst = out.setdefault(head, [])
            if not lst:
                lst.append({})
            lst[0][tail] = value
        else:
            out.setdefault(head, {})[tail] = value
    return out


def coerce_bool(value):
    if isinstance(value, str):
        return value.strip().lower() == "true"
    return bool(value)


def user_out(user: dict) -> dict:
    """Output view: adds the derived, read-only "groups" attribute."""
    res = dict(user)
    res["groups"] = [
        {"value": g["id"], "display": g["displayName"],
         "$ref": f"{BASE_URL}/Groups/{g['id']}"}
        for g in _groups.values()
        if any(m.get("value") == user["id"] for m in g.get("members", []))
    ]
    return res


def group_out(group: dict) -> dict:
    res = dict(group)
    members = []
    for m in group.get("members", []):
        u = _users.get(m.get("value"))
        members.append({"value": m["value"],
                        "display": u.get("userName") if u else m.get("display"),
                        "$ref": f"{BASE_URL}/Users/{m['value']}"})
    res["members"] = members
    return res


def meta(resource_type: str, rid: str, created: str | None = None) -> dict:
    stamp = now()
    return {"resourceType": resource_type, "created": created or stamp,
            "lastModified": stamp,
            "location": f"{BASE_URL}/{resource_type}s/{rid}"}


def validate_user(user: dict, own_id: str | None) -> None:
    if not user.get("userName"):
        raise ScimError(400, "userName is required", "invalidValue")
    for other in _users.values():
        if other["id"] == own_id:
            continue
        if other.get("userName", "").lower() == user["userName"].lower():
            raise ScimError(409, f"userName {user['userName']} already exists", "uniqueness")
        if user.get("externalId") and other.get("externalId") == user["externalId"]:
            raise ScimError(409, f"externalId {user['externalId']} already exists", "uniqueness")


def validate_group(group: dict, own_id: str | None) -> None:
    if not group.get("displayName"):
        raise ScimError(400, "displayName is required", "invalidValue")
    for other in _groups.values():
        if other["id"] != own_id and other["displayName"].lower() == group["displayName"].lower():
            raise ScimError(409, f"group {group['displayName']} already exists", "uniqueness")
    for m in group.get("members", []):
        if not isinstance(m, dict) or m.get("value") not in _users:
            raise ScimError(400, f"unknown member {m}", "invalidValue")


def normalize_user(body: dict, existing: dict | None) -> dict:
    body = unflatten(body)
    user = {k: v for k, v in body.items() if k not in READ_ONLY}
    user["schemas"] = [SCHEMA_USER]
    if "active" in user:
        user["active"] = coerce_bool(user["active"])
    else:
        user["active"] = existing.get("active", True) if existing else True
    return user


def normalize_group(body: dict) -> dict:
    body = unflatten(body)
    group = {k: v for k, v in body.items() if k not in READ_ONLY}
    group["schemas"] = [SCHEMA_GROUP]
    members = []
    for m in group.get("members") or []:
        if isinstance(m, str):
            m = {"value": m}
        if m.get("value") and m["value"] not in [x["value"] for x in members]:
            members.append({"value": m["value"]})
    group["members"] = members
    return group


# ---------------------------------------------------------------------------
# PATCH (RFC 7644 section 3.5.2)
# ---------------------------------------------------------------------------
_PATH = re.compile(r'^(?P<attr>[A-Za-z0-9_:.$\-]+?)(?:\[(?P<filter>[^\]]+)\])?(?:\.(?P<sub>[A-Za-z0-9_$]+))?$')


def apply_patch(resource: dict, operations: list) -> dict:
    res = json.loads(json.dumps(resource))
    for op in operations:
        if not isinstance(op, dict):
            raise ScimError(400, "operation must be an object", "invalidValue")
        kind = str(op.get("op", "")).lower()
        path = op.get("path")
        value = op.get("value")
        if kind not in ("add", "replace", "remove"):
            raise ScimError(400, f"unsupported op {kind}", "invalidValue")

        if not path:
            if kind == "remove":
                raise ScimError(400, "remove needs a path", "noTarget")
            if not isinstance(value, dict):
                raise ScimError(400, "value must be an object without a path", "invalidValue")
            for k, v in unflatten(value).items():
                if k in READ_ONLY:
                    continue
                if k in MULTI_VALUED and kind == "add":
                    _add_members(res, k, v)
                else:
                    res[k] = v
            continue

        m = _PATH.match(path)
        if not m:
            raise ScimError(400, f"unsupported path {path}", "invalidPath")
        attr, flt, sub = m.group("attr"), m.group("filter"), m.group("sub")
        if attr.startswith("urn:"):
            attr = attr.rsplit(":", 1)[-1]
        if attr in READ_ONLY:
            raise ScimError(400, f"{attr} is read-only", "mutability")

        if attr in MULTI_VALUED:
            lst = res.setdefault(attr, [])
            if flt:
                node = parse_filter(flt)
                hits = [x for x in lst if isinstance(x, dict) and matches(x, node)]
                if kind == "remove":
                    res[attr] = [x for x in lst if x not in hits]
                elif sub:
                    for x in hits:
                        x[sub] = value
                else:
                    for x in hits:
                        x.update(value if isinstance(value, dict) else {"value": value})
            elif kind == "remove":
                if value:
                    drop = {v.get("value") if isinstance(v, dict) else v
                            for v in (value if isinstance(value, list) else [value])}
                    res[attr] = [x for x in lst if x.get("value") not in drop]
                else:
                    res[attr] = []
            elif kind == "replace":
                res[attr] = value if isinstance(value, list) else [value]
            else:
                _add_members(res, attr, value)
        elif "." in attr or sub:
            head, tail = (attr.split(".", 1) if "." in attr else (attr, sub))
            if kind == "remove":
                res.get(head, {}).pop(tail, None)
            else:
                res.setdefault(head, {})[tail] = value
        else:
            if kind == "remove":
                res.pop(attr, None)
            else:
                res[attr] = value
    if "active" in res:
        res["active"] = coerce_bool(res["active"])
    return res


def _add_members(res: dict, attr: str, value) -> None:
    lst = res.setdefault(attr, [])
    items = value if isinstance(value, list) else [value]
    for item in items:
        if isinstance(item, str):
            item = {"value": item}
        if not isinstance(item, dict):
            continue
        if attr == "members" and item.get("value") not in _users:
            raise ScimError(400, f"unknown member {item.get('value')}", "invalidValue")
        if item.get("value") not in [x.get("value") for x in lst]:
            lst.append({k: v for k, v in item.items() if k != "$ref"})


